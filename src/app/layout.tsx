import type { Metadata, Viewport } from "next";
import Script from "next/script";
import { Playfair_Display, Cormorant_Garamond, Inter } from "next/font/google";
import { SITE } from "@/constants/site";
import { DEFAULT_SHARE_IMAGE } from "@/lib/seo";
import { CommerceProvider } from "@/hooks/useCommerce";
import { FloatingActionMenu } from "@/components/layouts";
import "@/styles/globals.css";

const playfair = Playfair_Display({
  subsets: ["latin"],
  variable: "--font-playfair",
  display: "swap",
  weight: ["400", "500", "600", "700"],
});

const cormorant = Cormorant_Garamond({
  subsets: ["latin"],
  variable: "--font-cormorant",
  display: "swap",
  weight: ["300", "400", "500", "600", "700"],
});

const inter = Inter({
  subsets: ["latin"],
  variable: "--font-inter",
  display: "swap",
});

/** Search Console ownership token (the `content` of Google's verification meta tag). */
const googleVerification = process.env.GOOGLE_SITE_VERIFICATION?.trim();

/**
 * Site-wide defaults. Public pages override these with `pageMetadata()` (lib/seo.ts) so each
 * link preview carries that page's own title, description, image and canonical URL. Icons come
 * from the file conventions in this folder (favicon.ico, icon.svg, apple-icon.png) plus
 * manifest.ts — generated by scripts/generate-brand-assets.mjs.
 */
export const metadata: Metadata = {
  metadataBase: new URL(SITE.url),
  title: {
    default: `${SITE.name} | ${SITE.tagline}`,
    template: `%s | ${SITE.name}`,
  },
  description: SITE.description,
  applicationName: SITE.name,
  keywords: [
    "luxury jewelry",
    "engagement rings",
    "diamond jewelry",
    "fine jewelry",
    "wedding rings",
    "custom jewellery",
    SITE.name,
  ],
  authors: [{ name: SITE.name, url: SITE.url }],
  creator: SITE.name,
  publisher: SITE.name,
  openGraph: {
    type: "website",
    locale: "en_US",
    siteName: SITE.name,
    title: `${SITE.name} | ${SITE.tagline}`,
    description: SITE.description,
    images: [DEFAULT_SHARE_IMAGE],
  },
  twitter: {
    card: "summary_large_image",
    title: `${SITE.name} | ${SITE.tagline}`,
    description: SITE.description,
    images: [{ url: DEFAULT_SHARE_IMAGE.url, alt: DEFAULT_SHARE_IMAGE.alt }],
  },
  appleWebApp: { title: SITE.name },
  ...(googleVerification && { verification: { google: googleVerification } }),
};

export const viewport: Viewport = {
  themeColor: "#0b0b0c",
  width: "device-width",
  initialScale: 1,
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" className={`${playfair.variable} ${cormorant.variable} ${inter.variable}`}>
      <body className="font-sans antialiased">
        <CommerceProvider>
          {children}
          <FloatingActionMenu />
        </CommerceProvider>
        {/* Right-click / double-click / DevTools-shortcut deterrent — see public/security.js */}
        <Script src="/security.js" strategy="beforeInteractive" />
      </body>
    </html>
  );
}
